## `llm-api-proxy` from source, for `armv7-unknown-linux-musleabihf`.
##
## Agent Harbor's LLM API proxy — the health-aware load balancer in front of
## the fleet's inference backends — as the fleet's Raspberry Pi add-on host
## runs it: one static musl executable, cross-compiled on an x86-64 build
## host (the Pi cannot compile a 1500-crate Rust workspace), published to
## the binary cache under the key the Pi's apply derives
## (reprobuild-pm Binary-Caches.md §"Publishing for a host that cannot
## build") and substituted there. infra's `services/llm-api-proxy` runs the
## same crate from the same revision as `llm-api-proxy-portable` on the
## NixOS hosts (`inputs.agent-harbor`, pinned to the commit below).
##
## ## What the version pins
##
## agent-harbor commit `23960db5e22b46357ffb93c71db141e3414bbd63`, the one
## infra's flake pins. The crate's own version is 0.2.0 (`version.workspace`),
## and the installed binary is `bin/llm-api-proxy`. The repository is
## private, so the source is a `git archive` of that commit rather than a
## release tarball, fetched over ssh with the build host's agent (read
## access to the repository is the one thing the build host must bring);
## the archive is verified against the SHA-256 recorded here.
##
## ## The dependency closure
##
## `cargo-vendor.manifest` beside this file pins every crate of the
## workspace lock (1496, six of them git sources), generated by
## `tools/cargo_vendor_manifest.nim` from upstream's `Cargo.lock`. The build
## is `--locked --offline`.
##
## ## Cross-compiling
##
## `cargo_package(target = …, zigCross = true)`: zig is the target's C
## compiler, archiver and linker (`repro_dsl_stdlib/adapters/cross_zig`),
## which is what the four C-bearing crates in the closure need —
## `openssl-sys` 0.9 (links the static OpenSSL this catalog builds for the
## target, `OPENSSL_NO_VENDOR=1` as upstream's own Nix build sets it),
## `aws-lc-sys` 0.41 (configures with cmake), `ring` 0.17 and
## `libsqlite3-sys` 0.28 (bundled). rustc is the catalog's host compiler with
## the target's standard library merged in
## (`packages/source/rust-sysroot-armv7-unknown-linux-musleabihf`), reached
## through `RUSTC`. `package` / `installPath` select the one workspace
## member.
##
## ## What the build produces, measured
##
## 2026-10-30, reprobuild `agents` `dfe55de54`, nixos-ci-bare-003 (x86-64),
## before the path remap: `bin/llm-api-proxy`, 16 943 392 bytes, static ARM
## EABI5, sha256 `ce53902b86c88d5176bece3c0acb615eaed0357095d1af1a2c8be0c975f20ab9`,
## carrying 742 absolute strings of this checkout's
## `.repro/cargo-vendor/vendor/<crate>/src/…` and the openssl recipe's path
## (rustc's panic locations); the hand-driven build it replaced (16 931 060
## bytes, `d22a6333…7731`) differed in those strings and nothing else.
## With the cross adapter's `--remap-path-prefix=<project root>=/build`
## those strings read `/build/.repro/cargo-vendor/vendor/…` wherever the
## checkout is, and `LlmApiProxyBinarySha256` below is the sha256 two
## checkouts must both produce.
## On a Raspberry Pi 2 (Raspberry Pi OS trixie armhf) under
## `DynamicUser=yes ProtectSystem=strict` it answers `/v1/models` from the
## fleet backend at ~12 MB RSS; the proxy is static, so it resolves backend
## names through `/etc/hosts` only.

import std/os

import repro_project_dsl
import repro_dsl_stdlib/constructors
import repro_dsl_stdlib/types/package_result

import ../source_recipe_paths

const
  LlmApiProxyVersion* = "0.2.0"
  AgentHarborCommit* = "23960db5e22b46357ffb93c71db141e3414bbd63"
  AgentHarborGitUrl* = "https://github.com/agent-harbor/agent-harbor"
  AgentHarborFetchUrl* = "git@github.com:agent-harbor/agent-harbor.git"
    ## Over ssh: the repository is private, an https remote would need a
    ## credential helper the fetch edge cannot run, and the build host's
    ## ssh agent is what authorises it.
  AgentHarborArchiveSha256* =
    "f36aacc95d23cd8cd8205ed200901aec82e730c1a552d74d1b6d8961f1a5fdb1"
    ## `git archive --format=tar <commit> | sha256sum`, taken with git
    ## 2.54.0 (and reproduced by the fetch edge's git 2.53.0). The stream's
    ## bytes depend on git's tar writer as well as on the tree, so a
    ## mismatch after a git upgrade is checked against the tree first:
    ## `git rev-parse <commit>^{tree}` is
    ## `AgentHarborTreeId` whatever git wrote the archive.
  AgentHarborTreeId* = "b2f983bd2b6b45cc4e68e61d5abd15e099c31ec2"
  Triple* = "armv7-unknown-linux-musleabihf"
  LlmApiProxyBinarySha256* = ""
    ## sha256 of `bin/llm-api-proxy` as this recipe builds it, from ANY
    ## checkout: the cross adapter remaps the project root out of the
    ## binary (reprobuild `cross_zig`, `--remap-path-prefix=<root>=/build`),
    ## so two builds must agree byte for byte. The test beside the recipe
    ## checks a present build output against it, so a toolchain or closure
    ## change that moves the bytes moves this constant with it, in review.
    ## EMPTY until measured: the two-checkout build that fills it could not
    ## run on 2026-10-30 because io-mon's shim kills the tarball rustc
    ## (reprobuild-pm issue
    ## 2026-10-30-io-mon-shim-kills-upstream-rustc-1.94.0-on-crates-with-macro-rules);
    ## an empty constant makes the test skip and say so, never pass.
  RustSysroot = "rust-sysroot-" & Triple
  OpensslStatic = "openssl-static-" & Triple

package llmApiProxySource:
  versions:
    "0.2.0":
      sourceRevision = AgentHarborCommit
      sourceUrl = AgentHarborGitUrl
      sourceRepository = AgentHarborGitUrl

  fetch:
    gitUrl: AgentHarborFetchUrl
    gitRevision: AgentHarborCommit
    sha256: AgentHarborArchiveSha256
    # `git archive` has no top-level directory (a release tarball has one,
    # hence the default of 1): the workspace root lands at `src/` as is.
    extractStrip: 0

  nativeBuildDeps:
    "cargo >=1.94 <1.95"
    "rustc >=1.94 <1.95"
    RustSysroot
    OpensslStatic
    # The target C toolchain, and what the `*-sys` build scripts run.
    "zig >=0.13 <0.14"
    "cmake >=3.20"
    "perl >=5.32"
    "make"
    # The vendor step unpacks 1496 `.crate` gzip tarballs (`tar -xzf`, tar
    # execs gzip) and clones the six git sources.
    "tar"
    "gzip"
    "git"

  config:
    discard

  executable `llm-api-proxy`:
    discard

  build:
    setCurrentOwningPackageOverride("llmApiProxySource")
    try:
      let sysroot = sourcePackageInstallPath(RustSysroot, "usr")
      let openssl = sourcePackageInstallPath(OpensslStatic, "usr")
      let pkg = cargo_package(
        target = Triple,
        zigCross = true,
        package = "llm-api-proxy",
        installPath = "crates/llm-api-proxy",
        extraEnv = @[
          ("RUSTC", sysroot / "bin" / "rustc"),
          ("ARMV7_UNKNOWN_LINUX_MUSLEABIHF_OPENSSL_DIR", openssl),
          ("ARMV7_UNKNOWN_LINUX_MUSLEABIHF_OPENSSL_STATIC", "1"),
          ("OPENSSL_NO_VENDOR", "1")])
      discard pkg.executable("llm-api-proxy")
    finally:
      clearCurrentOwningPackageOverride()

  runtimeDeps:
    discard
