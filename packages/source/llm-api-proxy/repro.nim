## `llm-api-proxy` from source, for whatever target the build names.
##
## Agent Harbor's LLM API proxy — the health-aware load balancer in front of
## the fleet's inference backends — as the fleet's Raspberry Pi add-on host
## runs it: one static musl executable, cross-compiled on an x86-64 build
## host (the Pi cannot compile a 1500-crate Rust workspace), published to
## the binary cache under the key the Pi's apply derives
## (reprobuild-pm Binary-Caches.md §"Publishing for a host that cannot
## build") and substituted there. infra's `services/llm-api-proxy` runs the
## same crate from the same revision as `llm-api-proxy-portable` on the
## NixOS hosts (`inputs.agent-harbor`, pinned to the commit below).
##
## ## What the version pins
##
## agent-harbor commit `23960db5e22b46357ffb93c71db141e3414bbd63`, the one
## infra's flake pins. The crate's own version is 0.2.0 (`version.workspace`),
## and the installed binary is `bin/llm-api-proxy`. The repository is
## private, so the source is a `git archive` of that commit rather than a
## release tarball, fetched over ssh with the build host's agent (read
## access to the repository is the one thing the build host must bring);
## the archive is verified against the SHA-256 recorded here.
##
## ## The dependency closure
##
## `cargo-vendor.manifest` beside this file pins every crate of the
## workspace lock (1496, six of them git sources), generated by
## `tools/cargo_vendor_manifest.nim` from upstream's `Cargo.lock`. The build
## is `--locked --offline`.
##
## ## Cross-compiling
##
## The recipe names no target. `repro build --target=<triple>` fills the
## active build context's `crossTarget` slot and `cargo_package` reads it
## (Reprobuild-Standard-Library.md §"CrossTarget"): both cargo steps carry
## `--target`, zig is the target's C compiler, archiver and linker
## (`repro_dsl_stdlib/adapters/cross_zig`), which is what the four
## C-bearing crates in the closure need — `openssl-sys` 0.9, `aws-lc-sys`
## 0.41 (configures with cmake), `ring` 0.17 and `libsqlite3-sys` 0.28
## (bundled) — and the target's standard library is the catalog's `rust-std`
## component, merged into a copy of the host `rustc` prefix and driven
## through `RUSTC` (`adapters/rust_target_sysroot`). Without `--target` the
## same recipe is a host build.
##
## The one thing the recipe says about the target is where `openssl-sys`
## finds OpenSSL: `OPENSSL_NO_VENDOR=1` (as upstream's own Nix build sets
## it) and the sibling `packages/source/openssl` recipe, named in
## `buildDeps:` and built for the same target -- its install mirror is
## keyed by the target, so `sourcePackageInstallPath` names the target
## build (From-Source-Build-Recipes.md §"Package-level dependency
## declarations"). `openssl-sys` reads the directory from
## `<TRIPLE>_OPENSSL_DIR` on a cross build and `OPENSSL_DIR` on a host
## build; the triple is spelled from the active target, never written
## here. `package` / `installPath` select the one workspace member.
##
## ## What the build produces, measured
##
## 2026-10-30, reprobuild `agents` `dfe55de54`, nixos-ci-bare-003 (x86-64),
## before the path remap: `bin/llm-api-proxy`, 16 943 392 bytes, static ARM
## EABI5, sha256 `ce53902b86c88d5176bece3c0acb615eaed0357095d1af1a2c8be0c975f20ab9`,
## carrying 742 absolute strings of this checkout's
## `.repro/cargo-vendor/vendor/<crate>/src/…` and the openssl recipe's path
## (rustc's panic locations); the hand-driven build it replaced (16 931 060
## bytes, `d22a6333…7731`) differed in those strings and nothing else.
## With the cross adapter's `--remap-path-prefix=<project root>=/build`
## those strings read `/build/.repro/cargo-vendor/vendor/…` wherever the
## checkout is, and `LlmApiProxyBinarySha256` below is the sha256 two
## checkouts must both produce.
## On a Raspberry Pi 2 (Raspberry Pi OS trixie armhf) under
## `DynamicUser=yes ProtectSystem=strict` it answers `/v1/models` from the
## fleet backend at ~12 MB RSS; the proxy is static, so it resolves backend
## names through `/etc/hosts` only.

