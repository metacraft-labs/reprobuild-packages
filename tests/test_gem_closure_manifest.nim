## The gem-closure manifest generator: a Nix Ruby-with-gems closure becomes a
## manifest whose lines are the gems' published archives, pinned by SHA-256,
## in install order; and `--check` refuses a committed manifest that has
## drifted from the closure.
##
## Mock, justified: `fixtures/gem-closure-pinned-nixpkgs.json` is the output
## of the generator's own Nix expression (`--raw-json`), recorded from
## `fixtures/gem-closure-pinned-nixpkgs.nix` -- Ruby 3.4 with nokogiri and
## sinatra at a pinned nixpkgs revision. Re-evaluating nixpkgs in every test
## run would make the test depend on a Nix installation and a multi-minute
## evaluation, while what is tested here is what the generator does with the
## closure Nix reports. Regenerate it with:
##
##     nim r tools/gem_closure_manifest.nim \
##       --file=tests/fixtures/gem-closure-pinned-nixpkgs.nix --raw-json \
##       > tests/fixtures/gem-closure-pinned-nixpkgs.json
##
## One digest (mini_portile2 2.8.9) was checked against the archive
## rubygems.org serves when the fixture was recorded.

import std/[json, os, sequtils, strutils, unittest]

import ../tools/gem_closure_manifest as generator

const FixtureDir = currentSourcePath.parentDir / "fixtures"

proc pinnedClosure(): JsonNode =
  parseJson(readFile(FixtureDir / "gem-closure-pinned-nixpkgs.json"))

proc position(gems: seq[NixGem]; name: string): int =
  for i, gem in gems:
    if gem.name == name:
      return i
  -1

suite "gem closure manifest generator":
  test "the pinned closure becomes one pinned line per gem":
    let gems = installOrder(parseGems(pinnedClosure()))
    check gems.len == 12
    check gems.mapIt(it.name).deduplicate().len == gems.len
    for gem in gems:
      check gem.platform == "ruby"
      check gem.sha256.len == 64
      check gem.url == "https://rubygems.org/gems/" & gem.name & "-" &
        gem.version & ".gem"
    let nokogiri = gems[position(gems, "nokogiri")]
    check nokogiri.version == "1.18.10"
    check nokogiri.sha256 ==
      "d5cc0731008aa3b3a87b361203ea3d19b2069628cb55e46ac7d84a0445e69cc1"
    check gems[position(gems, "mini_portile2")].sha256 ==
      "0cd7c7f824e010c072e33f68bc02d85a00aeb6fce05bb4819c03dfd3c140c289"

  test "every gem is installed after the gems it depends on":
    let gems = installOrder(parseGems(pinnedClosure()))
    for i, gem in gems:
      for dep in gem.deps:
        let at = position(gems, dep)
        check at >= 0
        check at < i
    # nokogiri's extconf.rb requires mini_portile2 at build time.
    check position(gems, "mini_portile2") < position(gems, "nokogiri")
    check position(gems, "racc") < position(gems, "nokogiri")
    check position(gems, "rack") < position(gems, "sinatra")

  test "the order does not depend on the order Nix reports":
    var reversed = newJArray()
    let closure = pinnedClosure()
    for i in countdown(closure.len - 1, 0):
      reversed.add(closure[i])
    check installOrder(parseGems(reversed)).mapIt(manifestLine(it)) ==
      installOrder(parseGems(closure)).mapIt(manifestLine(it))

  test "the rendered manifest is what --check compares":
    let gems = installOrder(parseGems(pinnedClosure()))
    let text = renderManifest(gems, "fixture")
    check text.startsWith("# Generated by tools/gem_closure_manifest.nim")
    let lines = entryLines(text)
    check lines.len == 12
    check firstDifference(lines, lines) == ""
    # Each kind of drift the consumer's check exists to catch.
    var removed = lines
    removed.delete(position(gems, "sinatra"))
    check "sinatra" in firstDifference(removed, lines)
    var bumped = lines
    bumped[0] = bumped[0].replace("0.3.0", "0.3.1")
    check firstDifference(bumped, lines).len > 0
    var tampered = lines
    tampered[1] = tampered[1].replace(gems[1].sha256, "0".repeat(64))
    check firstDifference(tampered, lines).len > 0
    # A comment or whitespace change is not drift.
    check entryLines("# header\n\n" & lines.join("\n  ")) == lines

  test "a git gem, a non-sha256 pin and a duplicate name are refused":
    var git = pinnedClosure()
    git[0]["type"] = %"git"
    expect GeneratorError:
      discard parseGems(git)
    var weak = pinnedClosure()
    weak[0]["sha256"] = %"unsupported:sha512"
    expect GeneratorError:
      discard parseGems(weak)
    var twice = pinnedClosure()
    twice.add(twice[0])
    expect GeneratorError:
      discard parseGems(twice)
    var wrongUrl = pinnedClosure()
    wrongUrl[0]["urls"] = %["https://example.invalid/other.gem"]
    expect GeneratorError:
      discard parseGems(wrongUrl)
